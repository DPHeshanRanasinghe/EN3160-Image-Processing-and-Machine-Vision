"""Validate relocation and retained scientific records without test inference."""

import argparse
import ast
import json
import subprocess
import sys
import tempfile
from pathlib import Path

import torch
from PIL import Image

if __package__:
    from . import evaluate, plot_results, pooling_models, provenance
else:
    import evaluate
    import plot_results
    import pooling_models
    import provenance

EXPERIMENT = Path(__file__).resolve().parent
ROOT = EXPERIMENT.parents[1]


def require_rejection(action):
    try:
        action()
    except ValueError:
        return
    raise AssertionError('Invalid provenance was accepted')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--report', default=None, help='Write a new JSON report; never overwrite')
    args = parser.parse_args()
    inventory = json.loads((EXPERIMENT / 'migration_manifest.json').read_text())
    preserved = []
    for record in inventory['files']:
        path = Path(record['path'])
        # Generated bytecode is ignored by Git and can change on import. It is
        # recorded in the old inventory, but is not scientific provenance.
        if path.parts[0] not in ('cache', 'checkpoints', 'results', 'figures'):
            continue
        current = EXPERIMENT / path
        assert current.stat().st_size == record['size'], str(path)
        assert provenance.sha256(current) == record['sha256'], str(path)
        preserved.append(str(path))

    loaded = []
    final_checkpoints = []
    for directory in sorted((EXPERIMENT / 'checkpoints').iterdir()):
        models, checkpoints, paths = evaluate.load_checkpoints(directory.name)
        loaded.extend(str(p.relative_to(ROOT)) for p in paths.values())
        if directory.name != '20261012T035804_764978Z_f72eb563':
            final_checkpoints.append(checkpoints)
    # Synthetic model checks run only on artificial inputs.
    pooling_models.smoke_test()
    cache_path = EXPERIMENT / 'cache/full_modelnet40_seed42_val10_bs4.pt'
    cache = torch.load(cache_path, map_location='cpu')
    for checkpoints in final_checkpoints:
        evaluate.validate_cache_metadata(cache, cache_path, checkpoints)
    # Source label provenance only: do not call load_test_data/evaluate_model.
    expected = evaluate.original_source_labels(cache, 'test')
    assert torch.equal(cache['test']['indices'].sort().values, torch.arange(2468))
    assert (cache['test']['labels'].numpy() == expected[cache['test']['indices'].numpy()]).all()
    del cache

    checkpoint = next(iter(final_checkpoints[0].values()))
    config, binding = checkpoint['configuration'], checkpoint['_relocation_binding']
    require_rejection(lambda: provenance.validate_cache_binding(config, ROOT / 'other.pt', binding))
    require_rejection(lambda: provenance.validate_cache_binding(
        {**config, 'cache_path': '/unregistered/cache.pt'}, cache_path, binding))
    # Small isolated fixture exercises changed bytes at the exact registered path.
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / 'cache.pt'
        path.write_bytes(b'original cache')
        fixture = {'historical_cache_path': '/historical/cache.pt', 'cache_path': str(path),
                   'cache_sha256': provenance.sha256(path)}
        provenance.validate_cache_binding({'cache_path': '/historical/cache.pt'}, path, fixture)
        path.write_bytes(b'substituted cache')
        require_rejection(lambda: provenance.validate_cache_binding(
            {'cache_path': '/historical/cache.pt'}, path, fixture))
    sources = []
    old = plot_results.load_experiment('20261012T042856_572366Z_e467f11c',
        'evaluation_20261012T043112_742087Z_346dc31c', sources, ('baseline', 'attention'))
    new = plot_results.load_experiment('20261013T141057_022304Z_917cf31b',
        'evaluation_20261013T141438_951650Z_625b2d10', sources, ('max_min_std',))
    assert old['identities'] == new['identities']
    for path in EXPERIMENT.glob('*.py'):
        ast.parse(path.read_text(), filename=str(path))
    for name in ('train', 'evaluate', 'extract_full_features', 'plot_results', 'validate_migration'):
        for command in ([sys.executable, '-B', str(EXPERIMENT / (name + '.py')), '--help'],
                        [sys.executable, '-B', '-m', 'experiments.pooling_comparison.' + name, '--help']):
            result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True)
            assert result.returncode == 0, result.stderr
    figure_dir = EXPERIMENT / 'figures/three_model_comparison'
    manifest = json.loads((figure_dir / 'figure_manifest.json').read_text())
    for source in manifest['source_artifacts']:
        assert provenance.sha256(ROOT / source['path']) == source['sha256']
    assert len(manifest['figures']) == 14
    for figure in manifest['figures']:
        path = figure_dir / figure['path']
        assert provenance.sha256(path) == figure['sha256']
        if path.suffix == '.png':
            with Image.open(path) as image:
                assert min(image.size) >= 1000
                assert min(image.info['dpi']) >= 299
                image.verify()
        else:
            data = path.read_bytes()
            assert data.startswith(b'%PDF-')
            assert b'/Subtype /Image' not in data, 'PDF figure contains raster image cells'
    # Both ordinary overwrite protection and historical-directory protection.
    for options in ([], ['--overwrite', '--output-dir', str(EXPERIMENT / 'figures/full_modelnet40')]):
        result = subprocess.run([sys.executable, '-B', str(EXPERIMENT / 'plot_results.py'), *options],
                                cwd=ROOT, capture_output=True, text=True)
        assert result.returncode != 0
        assert ('FileExistsError' in result.stderr if not options else 'Historical figures are immutable' in result.stderr)
    report = {'preserved_artifact_count': len(preserved), 'preserved_artifacts': preserved,
              'strictly_loaded_checkpoints': loaded,
              'checks': ['SHA-256 and sizes of all historical artifacts',
                         'Five strict checkpoint loads', 'Synthetic three-model smoke test',
                         'Both full-run cache metadata and source-label checks',
                         'Unregistered path and changed cache content rejected',
                         'Saved metrics, confusion matrices, curves and aligned test identities',
                         'Python syntax and ten script/module CLI entry points',
                         'Seven PNG/PDF pairs: hashes, PNG dimensions/DPI, vector PDFs',
                         'Figure source hashes and overwrite-protection rejection'],
              'training_executed': False, 'official_test_inference_executed': False,
              'limitations': ['No training-time cache hash in historical checkpoints',
                             'Preliminary smoke-run cache is absent']}
    if args.report:
        with Path(args.report).open('x') as stream:
            json.dump(report, stream, indent=2)
            stream.write('\n')
    print(json.dumps({key: value for key, value in report.items()
                      if key != 'preserved_artifacts'}, indent=2))


if __name__ == '__main__':
    main()
